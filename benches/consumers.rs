//! CKB/Molecule call shapes, with monomorphized codecs and identical output.
//! Input preparation and reference checks are outside the timer. Allocation,
//! formatting, Serde and output destruction are included where the caller uses them.
//!
//! Source audit: CKB develop 95fd03933ce2a396b84aed12caaa0f984165cd6c;
//! Molecule master e2895756b66bc4935a31a2fa13420d869cc6c511 (bindings 0.9.2).
//! Both currently select faster-hex 0.6.1, included as `legacy_0_6`.
//! CKB: util/fixed-hash/core/src/serde.rs; util/jsonrpc-types/src/{fixed_bytes,
//! proposal_short_id,bytes,pool}.rs. The two RPC serialization stages come from
//! jsonrpc-utils-macros 0.3.0 and jsonrpc-core 18.0.0. Only serialization is timed,
//! excluding transaction-pool access, wire transport and conversion of packed types.
//! Molecule: bindings/rust/src/lib.rs and tools/codegen/src/generator/languages/
//! rust/display.rs. `molecule_display` writes the generated Bytes display shape
//! into reusable destination storage, including the temporary string it creates.
//! `faster_hex_borrowed` is a possible caller change, not today's Molecule behavior.
//! Both display variants retain the generated type's Display wrapper.
//!
//! These are isolated caller-shaped workloads, not full CKB benchmarks. H256
//! parsing/formatting uses CKB's own scalar code; Molecule without std does not
//! use faster-hex. DNS seeding's 64-byte public-key decode is currently disabled.
//! Those paths must not be credited with improvements measured here.
use criterion::{criterion_group, criterion_main, BenchmarkId, Criterion};
use fashex::Hex as _;
use hex_simd::{AsOut, AsciiCase};
use serde::{Deserialize, Deserializer, Serialize, Serializer};
use std::{convert::TryInto, fmt, fmt::Write, hint::black_box, marker::PhantomData};

mod support;

trait Codec {
    const NAME: &'static str;
    fn encode(src: &[u8], dst: &mut [u8]) -> Result<(), ()>;
    fn decode(src: &[u8], dst: &mut [u8]) -> Result<(), ()>;
    fn string(src: &[u8]) -> String;
}

macro_rules! codec {
    ($ty:ident, $name:literal, $encode:expr, $decode:expr, $string:expr) => {
        struct $ty;
        impl Codec for $ty {
            const NAME: &'static str = $name;
            #[inline]
            fn encode(src: &[u8], dst: &mut [u8]) -> Result<(), ()> {
                $encode(src, dst)
            }
            #[inline]
            fn decode(src: &[u8], dst: &mut [u8]) -> Result<(), ()> {
                $decode(src, dst)
            }
            #[inline]
            fn string(src: &[u8]) -> String {
                $string(src)
            }
        }
    };
}

